// Estrutura do banco (Postgres). Idempotente: roda a cada inicialização.
//
// Status do lead ao longo do funil:
// novo -> analisado -> proposta_gerada -> contatado -> respondeu
// (ou descartado / sem_interesse / descadastrado)
export const SCHEMA = `
CREATE TABLE IF NOT EXISTS leads (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  place_id         text UNIQUE,
  nome             text NOT NULL,
  nicho            text,
  cidade           text,
  endereco         text,
  telefone         text,
  whatsapp         text,
  email            text,
  site             text,
  maps_url         text,
  avaliacao        double precision,
  total_avaliacoes integer,
  analise          text,              -- JSON com a auditoria do site
  oportunidades    text,              -- JSON com os serviços sugeridos
  origem           text NOT NULL DEFAULT 'campanha', -- campanha | maps (capturado pelo painel)
  status           text NOT NULL DEFAULT 'novo',
  token            text NOT NULL UNIQUE,              -- usado no link de descadastro
  observacao       text,
  criado_em        timestamptz NOT NULL DEFAULT now(),
  atualizado_em    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS mensagens (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id     integer NOT NULL REFERENCES leads(id),
  canal       text NOT NULL,             -- email | whatsapp
  destino     text NOT NULL,
  assunto     text,
  corpo       text NOT NULL,
  status      text NOT NULL DEFAULT 'rascunho', -- rascunho | aprovada | enviada | rejeitada | erro
  tipo        text NOT NULL DEFAULT 'inicial',  -- inicial | followup
  message_id  text,                      -- Message-ID do e-mail enviado, para reconhecer respostas
  responde_a  integer REFERENCES mensagens(id), -- follow-up aponta para a mensagem original
  erro        text,
  enviada_em  timestamptz,
  criado_em   timestamptz NOT NULL DEFAULT now()
);

-- Respostas recebidas dos leads (e-mail ou WhatsApp), classificadas pela IA.
CREATE TABLE IF NOT EXISTS respostas (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id       integer NOT NULL REFERENCES leads(id),
  canal         text NOT NULL,
  origem_id     text UNIQUE,             -- Message-ID do e-mail ou id da mensagem do WhatsApp
  de            text,
  assunto       text,
  texto         text NOT NULL,
  classificacao text,                    -- interessado | quer_informacoes | sem_interesse | descadastro | automatica | outro
  resumo        text,
  sugestao      text,                    -- rascunho de resposta sugerido pela IA
  lida          boolean NOT NULL DEFAULT false,
  recebida_em   timestamptz NOT NULL DEFAULT now()
);

-- Pares chave/valor para o estado interno (ex.: último UID lido no IMAP).
CREATE TABLE IF NOT EXISTS estado (
  chave text PRIMARY KEY,
  valor text
);

-- Lista de supressão: quem pediu para não ser contatado nunca recebe nada.
CREATE TABLE IF NOT EXISTS descadastros (
  contato   text PRIMARY KEY,            -- e-mail em minúsculas ou telefone só com dígitos
  motivo    text,
  criado_em timestamptz NOT NULL DEFAULT now()
);

-- Sequência gradual: cada lead recebe até 3 etapas por canal; a próxima só é
-- agendada depois que a anterior sai, e tudo para quando o lead responde.
ALTER TABLE mensagens ADD COLUMN IF NOT EXISTS etapa integer NOT NULL DEFAULT 1;
-- De onde veio o número de WhatsApp: verificado (UAZap confirmou) | site (link wa.me) | celular | fixo (pode não ter)
ALTER TABLE leads ADD COLUMN IF NOT EXISTS whatsapp_status text;
-- Instagram da empresa (o @) e os dados públicos do perfil (seguidores, posts, bio), em JSON.
ALTER TABLE leads ADD COLUMN IF NOT EXISTS instagram text;
ALTER TABLE leads ADD COLUMN IF NOT EXISTS instagram_dados text;
-- Resposta automática: qual mensagem a IA mandou e se a conversa precisa de você.
ALTER TABLE respostas ADD COLUMN IF NOT EXISTS mensagem_id integer;
ALTER TABLE respostas ADD COLUMN IF NOT EXISTS precisa_humano text;
-- Avaliação da IA a cada resposta: chance de fechar (quente | morna | fria) e o próximo passo.
ALTER TABLE respostas ADD COLUMN IF NOT EXISTS temperatura text;
ALTER TABLE respostas ADD COLUMN IF NOT EXISTS proximo_passo text;
-- Respostas automáticas antigas não ficam como "não lidas" (a página de Respostas não as mostra).
UPDATE respostas SET lida = true WHERE classificacao = 'automatica' AND NOT lida;
ALTER TABLE mensagens ADD COLUMN IF NOT EXISTS agendada_para timestamptz;
-- Message-ID do e-mail do lead que esta mensagem responde (para cair na mesma conversa).
ALTER TABLE mensagens ADD COLUMN IF NOT EXISTS em_resposta_a text;
-- Quando a mensagem foi reservada para envio (status 'enviando'), para nenhuma sair duas vezes.
ALTER TABLE mensagens ADD COLUMN IF NOT EXISTS reservada_em timestamptz;
-- tipo: inicial (etapa 1) | sequencia (etapas 2 e 3) | followup (versão antiga) | resposta (enviada na conversa)
-- Vários números de WhatsApp (UAZap): o número que cuida da conversa com a empresa e o que enviou cada mensagem.
ALTER TABLE leads ADD COLUMN IF NOT EXISTS numero_wa text;
ALTER TABLE mensagens ADD COLUMN IF NOT EXISTS numero_wa text;

-- Posts de conteúdo para o Instagram da empresa: a IA cria um por dia (Reels ou carrossel).
CREATE TABLE IF NOT EXISTS posts (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dia        date NOT NULL,                     -- dia (em Brasília) a que o post pertence
  formato    text NOT NULL,                     -- reels | carrossel
  pilar      text NOT NULL,                     -- linha editorial (erro, dica, mito...)
  tema       text NOT NULL,
  conteudo   text NOT NULL,                     -- JSON: gancho, telas, legenda, hashtags...
  status     text NOT NULL DEFAULT 'pronto',    -- pronto | postado | descartado
  criado_em  timestamptz NOT NULL DEFAULT now(),
  postado_em timestamptz
);
CREATE INDEX IF NOT EXISTS idx_posts_dia ON posts(dia);
-- Postagem automática no Instagram: o container é a mídia já criada lá e ainda não publicada.
ALTER TABLE posts ADD COLUMN IF NOT EXISTS instagram_container text;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS instagram_id text;
-- Horário do dia em que o post sai (12, 18...); null = criado pelo botão, entra no próximo horário vago.
ALTER TABLE posts ADD COLUMN IF NOT EXISTS horario integer;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS instagram_link text;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS instagram_erro text;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS instagram_tentativas integer NOT NULL DEFAULT 0;
-- O mesmo post na página da empresa no LinkedIn, com resultado próprio.
ALTER TABLE posts ADD COLUMN IF NOT EXISTS linkedin_midia text;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS linkedin_id text;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS linkedin_link text;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS linkedin_erro text;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS linkedin_tentativas integer NOT NULL DEFAULT 0;

-- Imagens e vídeos gerados para o Instagram buscar pelo link; apagados depois que o post sai.
-- Insights dos posts do perfil no Instagram (os criados pelo sistema e os outros), atualizados ao longo do dia.
CREATE TABLE IF NOT EXISTS instagram_metricas (
  midia_id      text PRIMARY KEY,
  post_id       integer,                 -- o post do sistema, quando foi ele que publicou
  formato       text,                    -- reels | carrossel | imagem
  legenda       text,
  link          text,
  publicado_em  timestamptz,
  metricas      text NOT NULL,           -- JSON: alcance, visualizações, curtidas, comentários...
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

-- Contratos: cada cliente tem o seu, criado a partir do modelo e editável depois.
-- Perguntas de compradores no Mercado Livre, com a resposta sugerida pela IA. Só saem com a aprovação do vendedor.
CREATE TABLE IF NOT EXISTS ml_perguntas (
  id                text PRIMARY KEY,
  item_id           text NOT NULL,
  item_titulo       text,
  item_link         text,
  texto             text NOT NULL,
  criada_em         timestamptz,
  rascunho          text,
  precisa_conferir  boolean NOT NULL DEFAULT false,
  motivo            text,
  resposta          text,
  respondida_em     timestamptz,
  status            text NOT NULL DEFAULT 'pendente',
  erro              text
);

-- De qual conta conectada a pergunta veio.
ALTER TABLE ml_perguntas ADD COLUMN IF NOT EXISTS conta_id text;

-- Produtos cadastrados no painel, para publicar nos marketplaces.
CREATE TABLE IF NOT EXISTS produtos (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome               text NOT NULL,
  descricao          text,
  preco              numeric NOT NULL,
  estoque            integer NOT NULL DEFAULT 0,
  sku                text,
  marca              text,
  modelo             text,
  gtin               text,
  condicao           text NOT NULL DEFAULT 'new',
  peso_g             integer,
  altura_cm          integer,
  largura_cm         integer,
  comprimento_cm     integer,
  ncm                text,
  cfop_mesmo_estado  text,
  cfop_outro_estado  text,
  csosn              text,
  origem             text,
  fotos              text NOT NULL DEFAULT '[]',
  criado_em          timestamptz NOT NULL DEFAULT now(),
  atualizado_em      timestamptz NOT NULL DEFAULT now()
);

-- Onde cada produto foi publicado.
CREATE TABLE IF NOT EXISTS produto_publicacoes (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produto_id  integer NOT NULL,
  canal       text NOT NULL,
  conta_id    text NOT NULL,
  externo_id  text,
  link        text,
  status      text NOT NULL,
  erro        text,
  criado_em   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (produto_id, canal, conta_id)
);

-- Fornecedores de dropshipping achados e salvos na aba Fornecedores. Ficam fora do funil: nunca recebem mensagem automática.
CREATE TABLE IF NOT EXISTS fornecedores (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chave         text NOT NULL UNIQUE,
  nome          text NOT NULL,
  tipo          text,
  nichos        text,
  cidade        text,
  site          text,
  whatsapp      text,
  telefone      text,
  email         text,
  instagram     text,
  fonte         text,
  confirmacao   text NOT NULL DEFAULT 'possivel',
  evidencia     text,
  status        text NOT NULL DEFAULT 'novo',
  observacao    text,
  criado_em     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS contratos (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id       integer,                 -- a empresa do sistema, quando veio de uma conversa
  projeto       text NOT NULL,
  contratante   text NOT NULL,
  corpo         text NOT NULL,
  resumo        text,                    -- o valor, em uma linha, para a lista
  valor_total   double precision,
  status        text NOT NULL DEFAULT 'rascunho', -- rascunho | enviado | assinado | cancelado
  criado_em     timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS midias (
  chave     text PRIMARY KEY,
  tipo      text NOT NULL,                      -- image/jpeg | video/mp4
  dados     text NOT NULL,                      -- arquivo em base64
  criada_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_leads_status ON leads(status);
CREATE INDEX IF NOT EXISTS idx_mensagens_status ON mensagens(status);
CREATE INDEX IF NOT EXISTS idx_mensagens_destino ON mensagens(destino);
CREATE INDEX IF NOT EXISTS idx_mensagens_message_id ON mensagens(message_id);
CREATE INDEX IF NOT EXISTS idx_mensagens_lead ON mensagens(lead_id);
CREATE INDEX IF NOT EXISTS idx_mensagens_responde_a ON mensagens(responde_a);
CREATE INDEX IF NOT EXISTS idx_respostas_lead ON respostas(lead_id);

-- No Supabase as tabelas do schema public ficam expostas pela API REST.
-- RLS ligado e sem políticas = ninguém acessa por ela; o sistema conecta direto no Postgres.
ALTER TABLE leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE mensagens ENABLE ROW LEVEL SECURITY;
ALTER TABLE respostas ENABLE ROW LEVEL SECURITY;
ALTER TABLE estado ENABLE ROW LEVEL SECURITY;
ALTER TABLE descadastros ENABLE ROW LEVEL SECURITY;
ALTER TABLE posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE midias ENABLE ROW LEVEL SECURITY;
`;
